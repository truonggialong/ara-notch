import Testing
@testable import ClipboardCore

@Suite struct ClipboardPrivacyTests {
    private let plain = ["public.utf8-plain-text"]
    private let safari = ClipSource(bundleID: "com.apple.Safari", appName: "Safari")

    @Test func ordinaryCopyIsCaptured() {
        #expect(ClipboardPrivacy.shouldCapture(
            pasteboardTypes: plain, source: safari, isPaused: false, ignoredBundleIDs: []))
    }

    @Test func nothingIsCapturedWhilePaused() {
        #expect(!ClipboardPrivacy.shouldCapture(
            pasteboardTypes: plain, source: safari, isPaused: true, ignoredBundleIDs: []))
    }

    @Test func ignoredAppIsNotCaptured() {
        #expect(!ClipboardPrivacy.shouldCapture(
            pasteboardTypes: plain, source: safari, isPaused: false, ignoredBundleIDs: ["com.apple.Safari"]))
    }

    @Test func otherAppsAreCapturedWhenSomeAreIgnored() {
        #expect(ClipboardPrivacy.shouldCapture(
            pasteboardTypes: plain, source: safari, isPaused: false, ignoredBundleIDs: ["com.1password.1password"]))
    }

    @Test func unknownSourceIsCapturedEvenWithAnIgnoreList() {
        #expect(ClipboardPrivacy.shouldCapture(
            pasteboardTypes: plain, source: ClipSource(), isPaused: false, ignoredBundleIDs: ["com.apple.Safari"]))
    }

    @Test func copiesMadeInTheAppsOwnInterfaceAreNotCaptured() {
        #expect(!ClipboardPrivacy.shouldCapture(
            pasteboardTypes: plain, source: safari, isPaused: false, ignoredBundleIDs: [],
            isFromOwnInterface: true))
    }

    @Test(arguments: [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ])
    func privateMarkerIsNotCaptured(_ marker: String) {
        #expect(!ClipboardPrivacy.shouldCapture(
            pasteboardTypes: plain + [marker], source: safari, isPaused: false, ignoredBundleIDs: []))
    }
}
